import os
import csv
from qgis.PyQt import uic
from qgis.PyQt.QtWidgets import QDialog, QFileDialog, QComboBox
from qgis.core import (QgsVectorLayer, QgsFeature, QgsGeometry, QgsPointXY,
                       QgsField, QgsProject, QgsFeatureRequest, QgsExpression)
from qgis.PyQt.QtCore import QVariant

FORM_CLASS, _ = uic.loadUiType(os.path.join(
    os.path.dirname(__file__), 'Visor_fpjd_dialog_base.ui'))

class VisorcontaminanteDialog(QDialog, FORM_CLASS):
    def __init__(self, parent=None):
        super().__init__(parent)
        self.setupUi(self)
        self.explorar.clicked.connect(self.open_file_dialog)
        self.fecha = self.findChild(QComboBox, 'fecha')
        self.cordx = self.findChild(QComboBox, 'cordx')
        self.cordy = self.findChild(QComboBox, 'cordy')
        self.iniciar.clicked.connect(self.process_data)
        self.csv_data = []

    def open_file_dialog(self):
        file_path, _ = QFileDialog.getOpenFileName(self, "Seleccionar archivo CSV", "", "CSV Files (*.csv)")
        if file_path:
            self.linea_explorar.setText(file_path)
            self.load_csv_data(file_path)

    def load_csv_data(self, file_path):
        try:
            with open(file_path, newline='', encoding='utf-8') as csvfile:
                reader = csv.DictReader(csvfile)
                self.csv_data = list(reader)
            
            unique_dates = sorted(set(row['Fecha'] for row in self.csv_data))
            headers = self.csv_data[0].keys()
            
            self.fecha.clear()
            self.fecha.addItems(unique_dates)
            self.cordx.clear()
            self.cordx.addItems(headers)
            self.cordy.clear()
            self.cordy.addItems(headers)

        except Exception as e:
            print(f"Error al cargar el archivo CSV: {e}")

    def process_data(self):
        selected_date = self.fecha.currentText()
        x_field = self.cordx.currentText()
        y_field = self.cordy.currentText()

        # Crear capa de puntos
        point_layer = self.create_point_layer(selected_date, x_field, y_field)

        # Crear línea
        line_layer = self.create_line_layer(point_layer, selected_date)

        # Crear buffer
        buffer_layer = self.create_buffer_layer(line_layer)

        # Añadir capas al proyecto, eliminando duplicados anteriores si existen
        self.remove_existing_layers(["Puntos", "Línea", "Buffer"])
        QgsProject.instance().addMapLayer(point_layer)
        QgsProject.instance().addMapLayer(line_layer)
        QgsProject.instance().addMapLayer(buffer_layer)

    def create_point_layer(self, selected_date, x_field, y_field):
        layer = QgsVectorLayer("Point?crs=EPSG:4326", "Puntos", "memory")
        provider = layer.dataProvider()
        provider.addAttributes([
            QgsField("Fecha", QVariant.String),
            QgsField("Tramo", QVariant.Int),
            QgsField("OD", QVariant.Double),
            QgsField("DBO", QVariant.Double),
            QgsField("Temperatura", QVariant.Double),
            QgsField("Caudal", QVariant.Double),
            QgsField("Velocidad", QVariant.Double),
            QgsField("Altura", QVariant.Double)
        ])
        layer.updateFields()

        for row in self.csv_data:
            if row['Fecha'] == selected_date:
                feat = QgsFeature()
                point = QgsPointXY(float(row[x_field]), float(row[y_field]))
                feat.setGeometry(QgsGeometry.fromPointXY(point))
                feat.setAttributes([
                    row.get('Fecha'),
                    self.parse_int(row.get('Tramo')),
                    self.parse_float(row.get('OD')),
                    self.parse_float(row.get('DBO')),
                    self.parse_float(row.get('Temperatura')),
                    self.parse_float(row.get('Caudal')),
                    self.parse_float(row.get('Velocidad')),
                    self.parse_float(row.get('Altura'))
                ])
                provider.addFeature(feat)

        layer.updateExtents()
        return layer

    def create_line_layer(self, point_layer, selected_date):
        line_layer = QgsVectorLayer("LineString?crs=EPSG:4326", "Línea", "memory")
        provider = line_layer.dataProvider()
        provider.addAttributes([QgsField("Fecha", QVariant.String),
                                QgsField("Tramo", QVariant.Int)])
        line_layer.updateFields()

        request = QgsFeatureRequest()
        request.setFilterExpression(f"\"Fecha\" = '{selected_date}'")
        request.addOrderBy('Tramo')
        features = point_layer.getFeatures(request)

        line_points = []
        for feat in features:
            line_points.append(feat.geometry().asPoint())

        if line_points:
            line_feat = QgsFeature()
            line_geom = QgsGeometry.fromPolylineXY(line_points)
            line_feat.setGeometry(line_geom)
            line_feat.setAttributes([selected_date, None])
            provider.addFeature(line_feat)

        line_layer.updateExtents()
        return line_layer

    def create_buffer_layer(self, line_layer):
        buffer_layer = QgsVectorLayer("Polygon?crs=EPSG:4326", "Buffer", "memory")
        provider = buffer_layer.dataProvider()
        provider.addAttributes([QgsField("Fecha", QVariant.String),
                                QgsField("Tramo", QVariant.Int)])
        buffer_layer.updateFields()

        for feature in line_layer.getFeatures():
            buffered_geom = feature.geometry().buffer(0.00001, 5)  # Aproximadamente 1 metro
            buff_feat = QgsFeature()
            buff_feat.setGeometry(buffered_geom)
            buff_feat.setAttributes([feature['Fecha'], None])
            provider.addFeature(buff_feat)

        buffer_layer.updateExtents()
        return buffer_layer

    def remove_existing_layers(self, layer_names):
        project = QgsProject.instance()
        for layer in project.mapLayers().values():
            if layer.name() in layer_names:
                project.removeMapLayer(layer.id())

    def parse_float(self, value):
        try:
            return float(value)
        except (TypeError, ValueError):
            return None

    def parse_int(self, value):
        try:
            return int(value)
        except (TypeError, ValueError):
            return None
